    private generateRouteIndex(entities: EntityRoute[]): GeneratedRoute {
        const imports: string[] = [];
        const registrations: string[] = [];

        imports.push("import { authRoutes } from './auth/auth.routes';");
        registrations.push("await app.register(authRoutes, { prefix: '/api/v1' });");

        for (const entity of entities) {
            const varName = entity.name.charAt(0).toLowerCase() + entity.name.slice(1);
            const kebabName = this.toKebabCase(entity.name);
            imports.push(`import { ${varName}Routes } from './${kebabName}/${kebabName}.routes';`);
            registrations.push(`await app.register(${varName}Routes, { prefix: '/api/v1' });`);
        }

        const content = `/**
 * Route Index
 * Generated by Loveable Backend Orchestrator
 */

import { FastifyInstance } from 'fastify';
${imports.join('\n')}

export async function registerRoutes(app: FastifyInstance): Promise<void> {
    // Health check
    app.get('/health', async () => ({
        status: 'ok',
        timestamp: new Date().toISOString(),
    }));

    // Register API routes
${registrations.map(r => `    ${r}`).join('\n')}

    app.log.info('✅ All routes registered');
}
`;

        return {
            path: 'src/routes/index.ts',
            content,
            type: 'route',
        };
    }


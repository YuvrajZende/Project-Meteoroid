    private generateAuthService(): string {
        const dbImport = this.config.database === 'prisma'
            ? "import { prisma } from '../lib/prisma';"
            : "import { supabaseAdmin } from '../lib/supabase';";

        return `/**
 * Auth Service
 * Generated by Loveable Backend Orchestrator
 */

import bcrypt from 'bcryptjs';
import jwt from 'jsonwebtoken';
${dbImport}
import type { RegisterInput, LoginInput } from './schemas';

const JWT_SECRET = process.env.JWT_SECRET || 'your-secret-key';
const JWT_EXPIRES_IN = process.env.JWT_EXPIRES_IN || '15m';
const JWT_REFRESH_EXPIRES_IN = process.env.JWT_REFRESH_EXPIRES_IN || '7d';
const BCRYPT_ROUNDS = parseInt(process.env.BCRYPT_ROUNDS || '12', 10);

export interface TokenPayload {
    userId: string;
    email: string;
    type: 'access' | 'refresh';
}

export interface AuthTokens {
    accessToken: string;
    refreshToken: string;
    expiresIn: number;
}

export interface UserResponse {
    id: string;
    email: string;
    username?: string;
    firstName?: string;
    lastName?: string;
    createdAt: Date;
}

export class AuthService {
    /**
     * Register a new user
     */
    async register(data: RegisterInput): Promise<{ user: UserResponse; tokens: AuthTokens }> {
        // Hash password
        const hashedPassword = await bcrypt.hash(data.password, BCRYPT_ROUNDS);

        ${this.config.database === 'prisma' ? `
        // Check if user exists
        const existingUser = await prisma.user.findUnique({
            where: { email: data.email },
        });

        if (existingUser) {
            throw new Error('User with this email already exists');
        }

        // Create user
        const user = await prisma.user.create({
            data: {
                email: data.email,
                password: hashedPassword,
                username: data.username,
                firstName: data.firstName,
                lastName: data.lastName,
            },
        });` : `
        // Check if user exists
        const { data: existingUser } = await supabaseAdmin
            .from('users')
            .select('id')
            .eq('email', data.email)
            .single();

        if (existingUser) {
            throw new Error('User with this email already exists');
        }

        // Create user
        const { data: user, error } = await supabaseAdmin
            .from('users')
            .insert({
                email: data.email,
                password: hashedPassword,
                username: data.username,
                first_name: data.firstName,
                last_name: data.lastName,
            })
            .select()
            .single();

        if (error) throw error;`}

        // Generate tokens
        const tokens = this.generateTokens(user.id, user.email);

        return {
            user: this.sanitizeUser(user),
            tokens,
        };
    }

    /**
     * Login user
     */
    async login(data: LoginInput): Promise<{ user: UserResponse; tokens: AuthTokens }> {
        ${this.config.database === 'prisma' ? `
        // Find user
        const user = await prisma.user.findUnique({
            where: { email: data.email },
        });` : `
        // Find user
        const { data: user, error } = await supabaseAdmin
            .from('users')
            .select('*')
            .eq('email', data.email)
            .single();

        if (error && error.code !== 'PGRST116') throw error;`}

        if (!user) {
            throw new Error('Invalid email or password');
        }

        // Verify password
        const isValid = await bcrypt.compare(data.password, user.password);
        if (!isValid) {
            throw new Error('Invalid email or password');
        }

        // Generate tokens
        const tokens = this.generateTokens(user.id, user.email);

        return {
            user: this.sanitizeUser(user),
            tokens,
        };
    }

    /**
     * Refresh access token
     */
    async refreshToken(refreshToken: string): Promise<AuthTokens> {
        try {
            const decoded = jwt.verify(refreshToken, JWT_SECRET) as TokenPayload;

            if (decoded.type !== 'refresh') {
                throw new Error('Invalid token type');
            }

            ${this.config.database === 'prisma' ? `
            // Verify user still exists
            const user = await prisma.user.findUnique({
                where: { id: decoded.userId },
            });` : `
            // Verify user still exists
            const { data: user } = await supabaseAdmin
                .from('users')
                .select('id, email')
                .eq('id', decoded.userId)
                .single();`}

            if (!user) {
                throw new Error('User not found');
            }

            return this.generateTokens(user.id, user.email);
        } catch (error) {
            throw new Error('Invalid or expired refresh token');
        }
    }

    /**
     * Get current user
     */
    async getCurrentUser(userId: string): Promise<UserResponse> {
        ${this.config.database === 'prisma' ? `
        const user = await prisma.user.findUnique({
            where: { id: userId },
        });` : `
        const { data: user, error } = await supabaseAdmin
            .from('users')
            .select('*')
            .eq('id', userId)
            .single();

        if (error) throw error;`}

        if (!user) {
            throw new Error('User not found');
        }

        return this.sanitizeUser(user);
    }

    /**
     * Verify access token
     */
    verifyToken(token: string): TokenPayload {
        try {
            const decoded = jwt.verify(token, JWT_SECRET) as TokenPayload;
            if (decoded.type !== 'access') {
                throw new Error('Invalid token type');
            }
            return decoded;
        } catch (error) {
            throw new Error('Invalid or expired token');
        }
    }

    /**
     * Generate access and refresh tokens
     */
    private generateTokens(userId: string, email: string): AuthTokens {
        const accessToken = jwt.sign(
            { userId, email, type: 'access' } as TokenPayload,
            JWT_SECRET,
            { expiresIn: JWT_EXPIRES_IN }
        );

        const refreshToken = jwt.sign(
            { userId, email, type: 'refresh' } as TokenPayload,
            JWT_SECRET,
            { expiresIn: JWT_REFRESH_EXPIRES_IN }
        );

        // Parse expiry (simple version, assumes 'm' for minutes)
        const expiresIn = parseInt(JWT_EXPIRES_IN.replace(/[^0-9]/g, ''), 10) * 60;

        return { accessToken, refreshToken, expiresIn };
    }

    /**
     * Remove sensitive fields from user object
     */
    private sanitizeUser(user: Record<string, unknown>): UserResponse {
        return {
            id: user.id as string,
            email: user.email as string,
            username: user.username as string | undefined,
            firstName: (user.firstName || user.first_name) as string | undefined,
            lastName: (user.lastName || user.last_name) as string | undefined,
            createdAt: new Date(user.createdAt as string || user.created_at as string),
        };
    }
}

// Singleton
export const authService = new AuthService();
`;
    }

